const assert=require('node:assert/strict');
const C=require('./core.js');
const make=(dates,values)=>dates.map((d,i)=>[d,values[i],100000,values[i]*1.01,values[i]*.99,values[i]]);
const dates=Array.from({length:180},(_,i)=>new Date(Date.UTC(2025,0,1+i)).toISOString().slice(0,10));
const bench=make(dates,dates.map((_,i)=>100+i*.2));
const leader=make(dates,dates.map((_,i)=>100+i*.4));
const lagger=make(dates,dates.map((_,i)=>100+i*.1));
assert.equal(C.align(leader,bench).length,180);
assert.ok(C.relativeReturn(leader,bench,20)>0);
assert.ok(C.relativeReturn(lagger,bench,20)<0);
assert.ok(C.mansfield(leader,bench,60)>0);
const ba=C.betaAlpha(leader,bench,60,252);
assert.ok(ba.beta!==null&&ba.correlation!==null);
assert.ok(C.correlation(leader,bench,60)>.99);
const rrg=C.rrg(leader,bench,26,4);
assert.ok(rrg.length>0);
assert.ok(Number.isFinite(rrg.at(-1).x)&&Number.isFinite(rrg.at(-1).y));
assert.ok(Math.abs(rrg.at(-1).x-100)<50&&Math.abs(rrg.at(-1).y-100)<50);
assert.equal(C.classify(leader,bench,'D').state,'POTVRĐENA SNAGA');
const shifted=make(dates,dates.map((_,i)=>100+i));
shifted[20][0]='2024-12-31';
assert.ok(C.align(leader,shifted).length<180);
assert.equal(C.mfi(leader).available,true);
assert.equal(C.mfi(leader.map(x=>x.slice(0,3))).available,false);
console.log('OK: date alignment, relative return, Mansfield, beta/correlation, RRG, classification and MFI safeguards');
